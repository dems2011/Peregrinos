async function account(email, doc) {
  const c = client();
  await c.post("/auth/register-pilgrim", reg(email, doc));
  const link = await mailLink(email, "verificar-email?token=");
  await c.get(`/auth/verify-email?token=${encodeURIComponent(tokenFrom(link))}`);
  const r = await c.post("/auth/account/login", { email, password: PWD });
  if (r.status !== 200) throw new Error(`login ${email} ${r.status}`);
  return c;
}

